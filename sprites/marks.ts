export type MarkGrid = Uint8Array;

function build(rows: string[]): MarkGrid {
  const g = new Uint8Array(MARK_SIZE * MARK_SIZE);
  for (let y = 0; y < MARK_SIZE; y++) {
    const row = rows[y] ?? "";
    for (let x = 0; x < MARK_SIZE; x++) {
      const v = CH[row[x]];
      if (v !== undefined) g[y * MARK_SIZE + x] = v;
    }
  }
  // 背景が明るい所でも読めるよう、本体と同じ作法で1px縁取る
  const out = new Uint8Array(g);
  for (let y = 0; y < MARK_SIZE; y++) {
    for (let x = 0; x < MARK_SIZE; x++) {
      if (g[y * MARK_SIZE + x] !== 0) continue;
      let touch = false;
      for (const [ox, oy] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
        const nx = x + ox, ny = y + oy;
        if (nx < 0 || ny < 0 || nx >= MARK_SIZE || ny >= MARK_SIZE) continue;
        if (g[ny * MARK_SIZE + nx] !== 0) { touch = true; break; }
      }
      if (touch) out[y * MARK_SIZE + x] = C.outline;
    }
  }
  return out;
}

const cache = new Map<MarkId, MarkGrid[]>();

export function markGrids(id: MarkId): MarkGrid[] {
  const hit = cache.get(id);
  if (hit) return hit;
  const grids = MARKS[id].map(build);
  cache.set(id, grids);
  return grids;
}

export function markIds(): MarkId[] {
  return Object.keys(MARKS) as MarkId[];
}
